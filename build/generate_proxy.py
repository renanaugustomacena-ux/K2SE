"""Generate the version.dll proxy: forwarding stubs + linker .def.

Reads the export table of the REAL C:\\Windows\\SysWOW64\\version.dll rather
than hardcoding a name list, so the proxy always matches the host system.

Every export is forwarded, not just the three swkotor2.exe actually uses:
something else in the user's process (antivirus shim, RivaTuner, an overlay)
may import version.dll too, and a missing export would break it.

Usage:
    python build/generate_proxy.py
"""

import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "src")

REAL_DLL = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "SysWOW64", "version.dll")


def read_exports(path):
    """Parse a PE export directory and return the exported function names."""
    with open(path, "rb") as fh:
        data = fh.read()

    if data[:2] != b"MZ":
        raise SystemExit("not a PE file: %s" % path)
    pe = struct.unpack_from("<I", data, 0x3C)[0]
    if data[pe:pe + 4] != b"PE\0\0":
        raise SystemExit("bad PE signature: %s" % path)

    num_sections = struct.unpack_from("<H", data, pe + 6)[0]
    opt_size = struct.unpack_from("<H", data, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from("<H", data, opt)[0]
    if magic != 0x10B:
        raise SystemExit("expected a 32-bit PE (PE32), got magic 0x%X" % magic)

    export_rva, export_size = struct.unpack_from("<II", data, opt + 96)
    if export_rva == 0:
        raise SystemExit("no export directory in %s" % path)

    sections = []
    sec = opt + opt_size
    for i in range(num_sections):
        off = sec + i * 40
        name = data[off:off + 8].rstrip(b"\0").decode("ascii", "replace")
        vaddr, = struct.unpack_from("<I", data, off + 12)
        vsize, = struct.unpack_from("<I", data, off + 8)
        raw, = struct.unpack_from("<I", data, off + 20)
        sections.append((name, vaddr, vsize, raw))

    def rva_to_off(rva):
        for _name, vaddr, vsize, raw in sections:
            if vaddr <= rva < vaddr + max(vsize, 1):
                return raw + (rva - vaddr)
        raise SystemExit("RVA 0x%X is not inside any section" % rva)

    exp = rva_to_off(export_rva)
    num_names, = struct.unpack_from("<I", data, exp + 24)
    names_rva, = struct.unpack_from("<I", data, exp + 32)
    names_off = rva_to_off(names_rva)

    out = []
    for i in range(num_names):
        name_rva, = struct.unpack_from("<I", data, names_off + i * 4)
        off = rva_to_off(name_rva)
        end = data.index(b"\0", off)
        out.append(data[off:end].decode("ascii"))
    return sorted(out)


CPP_HEADER = '''// GENERATED by build/generate_proxy.py -- do not edit by hand.
//
// One naked jmp thunk per export of the real version.dll. The real DLL is
// resolved lazily on first call (never from DllMain, which holds the loader
// lock) via GetSystemDirectoryW -- not a hardcoded path, and not
// LoadLibrary("version.dll"), which would find us again and recurse.

#include <windows.h>

#include "log.h"

namespace {{

HMODULE g_real = nullptr;
void* g_fn[{count}] = {{nullptr}};
CRITICAL_SECTION g_lock;
bool g_lockReady = false;
volatile LONG g_calls[{count}] = {{0}};

void EnsureLoaded() {{
    if (g_real) return;

    if (!g_lockReady) {{
        InitializeCriticalSection(&g_lock);
        g_lockReady = true;
    }}
    EnterCriticalSection(&g_lock);
    if (!g_real) {{
        wchar_t path[MAX_PATH];
        UINT n = GetSystemDirectoryW(path, MAX_PATH);
        if (n && n < MAX_PATH) {{
            lstrcatW(path, L"\\\\version.dll");
            g_real = LoadLibraryW(path);
            k2se::log::Writef("proxy: real version.dll loaded from %S -> 0x%p", path, g_real);
        }}
        if (!g_real) k2se::log::Write("proxy: FAILED to load the real version.dll");
    }}
    LeaveCriticalSection(&g_lock);
}}

void* Resolve(int index, const char* name) {{
    EnsureLoaded();
    if (!g_fn[index] && g_real) {{
        g_fn[index] = reinterpret_cast<void*>(GetProcAddress(g_real, name));
        if (!g_fn[index]) k2se::log::Writef("proxy: unresolved export %s", name);
    }}
    InterlockedIncrement(&g_calls[index]);
    return g_fn[index];
}}

}}  // namespace

'''

def main():
    if not os.path.exists(REAL_DLL):
        raise SystemExit("cannot find %s" % REAL_DLL)

    names = read_exports(REAL_DLL)
    print("real version.dll exports: %d" % len(names))
    for n in names:
        print("   ", n)

    lines = [CPP_HEADER.format(count=len(names))]

    # A single shared resolver keeps each naked stub to four instructions.
    lines.append("extern \"C\" void* __stdcall k2se_ResolveThunk(int index);\n\n")
    lines.append("static const char* const kNames[] = {\n")
    for n in names:
        lines.append('    "%s",\n' % n)
    lines.append("};\n\n")
    lines.append(
        "extern \"C\" void* __stdcall k2se_ResolveThunk(int index) {\n"
        "    return Resolve(index, kNames[index]);\n"
        "}\n\n")

    for i, n in enumerate(names):
        lines.append(
            'extern "C" __declspec(naked) void k2se_stub_%s() {\n'
            "    __asm {\n"
            "        push %d\n"
            "        call k2se_ResolveThunk\n"
            "        jmp  eax\n"
            "    }\n"
            "}\n\n" % (n, i))

    cpp_path = os.path.join(SRC, "proxy_version_generated.cpp")
    with open(cpp_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(lines))
    print("\nwrote %s" % cpp_path)

    def_lines = ["; GENERATED by build/generate_proxy.py -- do not edit by hand.\n",
                 "LIBRARY version\n", "EXPORTS\n"]
    for n in names:
        def_lines.append("    %s = k2se_stub_%s\n" % (n, n))
    def_path = os.path.join(SRC, "version.def")
    with open(def_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(def_lines))
    print("wrote %s" % def_path)
    print("\n%d exports forwarded." % len(names))


if __name__ == "__main__":
    main()
